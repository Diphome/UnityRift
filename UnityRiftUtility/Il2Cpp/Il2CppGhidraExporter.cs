    /// <summary>
    /// Writes Il2CppDumper-compatible reverse-engineering helpers from the LibCpp2IL state that
    /// Cpp2IL leaves loaded: <c>script.json</c> (method/metadata/string symbols + function starts,
    /// consumed by the bundled <c>ghidra.py</c> / <c>ghidra_with_struct.py</c>), <c>stringliteral.json</c>,
    /// <c>il2cpp.h</c> (C struct layouts: <c>_o</c>/<c>_Fields</c>/<c>_c</c>/<c>_VTable</c>/<c>_StaticFields</c>/<c>_array</c>)
    /// and <c>il2cpp_ghidra.h</c> (same header pre-processed for Ghidra's C parser), plus
    /// <c>il2cpp_info.json</c> (image base, versions, counts). Output formats follow Il2CppDumper
    /// (MIT, Perfare) so its Ghidra/IDA scripts work unchanged.
    /// </summary>
    public static class Il2CppGhidraExporter
    {
        #region JSON model (Il2CppDumper's ScriptJson)

        public class ScriptJson
        {
            public List<ScriptMethod> ScriptMethod = new List<ScriptMethod>();
            public List<ScriptString> ScriptString = new List<ScriptString>();
            public List<ScriptMetadata> ScriptMetadata = new List<ScriptMetadata>();
            public List<ScriptMetadataMethod> ScriptMetadataMethod = new List<ScriptMetadataMethod>();
            public ulong[] Addresses;
        }

        public class ScriptMethod
        {
            public ulong Address;
            public string Name;
            public string Signature;
            public string TypeSignature;
        }

        public class ScriptString
        {
            public ulong Address;
            public string Value;
        }

        public class ScriptMetadata
        {
            public ulong Address;
            public string Name;
            public string Signature;
        }

        public class ScriptMetadataMethod
        {
            public ulong Address;
            public string Name;
            public ulong MethodAddress;
        }

        public class Il2CppInfo
        {
            public string Binary;
            public string Metadata;
            public string UnityVersion;
            public float MetadataVersion;
            public string ImageBase;      // hex; VA = ImageBase + RVA (Ghidra: currentProgram.getImageBase())
            public int PointerSize;
            public int Methods, GenericMethods, Strings, MetadataSymbols, MetadataMethods, FunctionStarts, Structs;
            public string HeaderVersionNote;
        }

        #endregion

        public static readonly string[] OutputFiles =
        {
            "script.json", "stringliteral.json", "il2cpp.h", "il2cpp_ghidra.h", "il2cpp_info.json",
        };
        public static readonly string[] ScriptFiles =
        {
            "ghidra.py", "ghidra_with_struct.py", "il2cpp_header_to_ghidra.py", "LICENSE-Il2CppDumper.txt",
        };

        /// <summary>Writes all outputs into <paramref name="folder"/>. Requires LibCpp2IL to be initialised (call inside Cpp2IL processing).</summary>
        public static Il2CppInfo Write(string folder, string binaryPath, string metadataPath, string unityVersion, Action<string> log = null)
        {
            var gen = new Generator(log, binaryPath);
            var info = gen.Run(folder);
            info.Binary = binaryPath;
            info.Metadata = metadataPath;
            info.UnityVersion = unityVersion;
            File.WriteAllText(Path.Combine(folder, "il2cpp_info.json"), JsonConvert.SerializeObject(info, Formatting.Indented));
            WriteScripts(folder);
            return info;
        }

        /// <summary>Writes the bundled Ghidra scripts (Il2CppDumper, MIT) into <paramref name="folder"/>/ghidra.</summary>
        public static void WriteScripts(string folder)
        {
            var dir = Path.Combine(folder, "ghidra");
            Directory.CreateDirectory(dir);
            var asm = typeof(Il2CppGhidraExporter).Assembly;
            foreach (var name in ScriptFiles)
            {
                using (var s = asm.GetManifestResourceStream("ghidra." + name))
                {
                    if (s == null) continue;
                    using (var f = File.Create(Path.Combine(dir, name)))
                        s.CopyTo(f);
                }
            }
            File.WriteAllText(Path.Combine(dir, "README.txt"), GhidraReadme);
        }

