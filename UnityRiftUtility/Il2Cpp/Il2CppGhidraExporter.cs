            private IEnumerable<MetadataUsage> EnumerateMetadataUsages()
            {
                // Pre-27 binaries: LibCpp2IL fills its global lists eagerly.
                var fromLists = new List<MetadataUsage>();
                foreach (var listName in new[] { "TypeRefs", "MethodRefs", "FieldRefs", "Literals" })
                {
                    var f = typeof(LibCpp2IlGlobalMapper).GetField(listName, BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static);
                    if (f?.GetValue(null) is List<MetadataUsage> list) fromLists.AddRange(list);
                }
                if (fromLists.Count > 0)
                    return fromLists;

                // v27+: usages are encoded in the binary; scan data sections only (Il2CppDumper's
                // approach). Walking the whole file is far too slow on large GameAssembly.dlls.
                var ranges = DataSectionRanges();
                if (ranges.Count == 0)
                {
                    log?.Invoke("[il2cpp] No PE/ELF data sections found; skipping metadata-usage scan (methods/structs are still written).");
                    return Array.Empty<MetadataUsage>();
                }
                var result = new List<MetadataUsage>();
                var seenAddr = new HashSet<ulong>();
                var step = (ulong)PointerSize();
                var scanned = 0;
                foreach (var (vaStart, size) in ranges)
                {
                    var end = vaStart + size;
                    for (var va = vaStart; va + step <= end; va += step)
                    {
                        scanned++;
                        MetadataUsage u;
                        try { u = LibCpp2IlGlobalMapper.CheckForPost27GlobalAt(va); }
                        catch { continue; }
                        if (u == null || !u.IsValid) continue;
                        if (seenAddr.Add(u.Offset != 0 ? u.Offset : va)) result.Add(u);
                    }
                }
                log?.Invoke($"[il2cpp] Metadata-usage scan: {result.Count} hits over {ranges.Count} data section(s) ({scanned} pointers).");
                return result;
            }

            /// <summary>Virtual-address ranges of initialized/writable non-executable sections (PE .rdata/.data, ELF PT_LOAD without PF_X).</summary>
            private List<(ulong va, ulong size)> DataSectionRanges()
            {
                try
                {
                    if (!string.IsNullOrEmpty(binaryPath) && File.Exists(binaryPath))
                    {
                        using (var fs = File.OpenRead(binaryPath))
                        using (var br = new BinaryReader(fs))
                        {
                            var mag = br.ReadUInt16();
                            fs.Position = 0;
                            if (mag == 0x5A4D) return PeDataSections(br);
                            if (mag == 0x457F) return ElfDataSections(br); // 0x7F 'E' little-endian as UInt16 = 0x457F
                        }
                    }
                }
                catch (Exception ex)
                {
                    log?.Invoke($"[il2cpp] Could not parse data sections: {ex.Message}");
                }
                return new List<(ulong, ulong)>();
            }

            private static List<(ulong va, ulong size)> PeDataSections(BinaryReader br)
            {
                var fs = br.BaseStream;
                fs.Position = 0x3C;
                var lfanew = br.ReadInt32();
                fs.Position = lfanew;
                if (br.ReadUInt32() != 0x4550) return new List<(ulong, ulong)>();
                br.ReadUInt16(); // Machine
                var numSections = br.ReadUInt16();
                fs.Position += 12; // TimeDateStamp + PointerToSymbolTable + NumberOfSymbols
                var optSize = br.ReadUInt16();
                br.ReadUInt16(); // Characteristics
                var optStart = fs.Position;
                var magic = br.ReadUInt16();
                ulong imageBase;
                if (magic == 0x20B)
                {
                    fs.Position = optStart + 24;
                    imageBase = br.ReadUInt64();
                }
                else if (magic == 0x10B)
                {
                    fs.Position = optStart + 28;
                    imageBase = br.ReadUInt32();
                }
                else return new List<(ulong, ulong)>();
                fs.Position = optStart + optSize;
                const uint MemExecute = 0x20000000;
                const uint CntCode = 0x00000020;
                const uint CntInitData = 0x00000040;
                var ranges = new List<(ulong, ulong)>();
                for (var i = 0; i < numSections; i++)
                {
                    fs.Position += 8; // Name
                    var virtualSize = br.ReadUInt32();
                    var virtualAddress = br.ReadUInt32();
                    var sizeOfRaw = br.ReadUInt32();
                    fs.Position += 16; // PointerToRawData through NumberOfLineNumbers
                    var characteristics = br.ReadUInt32();
                    if ((characteristics & (MemExecute | CntCode)) != 0) continue;
                    if ((characteristics & CntInitData) == 0) continue;
                    var size = Math.Max(virtualSize, sizeOfRaw);
                    if (size == 0) continue;
                    ranges.Add((imageBase + virtualAddress, size));
                }
                return ranges;
            }

            private static List<(ulong va, ulong size)> ElfDataSections(BinaryReader br)
            {
                var fs = br.BaseStream;
                var ident = br.ReadBytes(16);
                if (ident.Length < 16 || ident[0] != 0x7F || ident[1] != (byte)'E') return new List<(ulong, ulong)>();
                var is64 = ident[4] == 2;
                var little = ident[5] != 2;
                if (!little) return new List<(ulong, ulong)>(); // uncommon for Unity
                br.ReadUInt16(); // e_type
                br.ReadUInt16(); // e_machine
                br.ReadUInt32(); // e_version
                ulong e_phoff;
                if (is64)
                {
                    br.ReadUInt64(); // e_entry
                    e_phoff = br.ReadUInt64();
                    br.ReadUInt64(); // e_shoff
                }
                else
                {
                    br.ReadUInt32();
                    e_phoff = br.ReadUInt32();
                    br.ReadUInt32();
                }
                br.ReadUInt32(); // e_flags
                br.ReadUInt16(); // e_ehsize
                var e_phentsize = br.ReadUInt16();
                var e_phnum = br.ReadUInt16();
                const int PT_LOAD = 1;
                const int PF_X = 1;
                var ranges = new List<(ulong, ulong)>();
                for (var i = 0; i < e_phnum; i++)
                {
                    fs.Position = (long)e_phoff + i * e_phentsize;
                    uint p_type;
                    ulong p_vaddr, p_memsz;
                    uint p_flags;
                    if (is64)
                    {
                        p_type = br.ReadUInt32();
                        p_flags = br.ReadUInt32();
                        br.ReadUInt64(); // p_offset
                        p_vaddr = br.ReadUInt64();
                        br.ReadUInt64(); // p_paddr
                        br.ReadUInt64(); // p_filesz
                        p_memsz = br.ReadUInt64();
                    }
                    else
                    {
                        p_type = br.ReadUInt32();
                        br.ReadUInt32(); // p_offset
                        p_vaddr = br.ReadUInt32();
                        br.ReadUInt32(); // p_paddr
                        br.ReadUInt32(); // p_filesz
                        p_memsz = br.ReadUInt32();
                        p_flags = br.ReadUInt32();
                    }
                    if (p_type != PT_LOAD || (p_flags & PF_X) != 0 || p_memsz == 0) continue;
                    ranges.Add((p_vaddr, p_memsz));
                }
                return ranges;
            }

            private void AddUsage(ScriptJson json, MetadataUsage u)
            {
                ulong rva;
                try { rva = bin.GetRva(u.Offset); } catch { return; }
                try
                {
                    switch (u.Type)
                    {
                        case MetadataUsageType.TypeInfo:
                            {
                                var r = u.AsType();
                                var name = DisplayName(r);
                                var sn = StructName(r);
                                json.ScriptMetadata.Add(new ScriptMetadata { Address = rva, Name = name + "_TypeInfo", Signature = sn.EndsWith("_array") ? "Il2CppClass*" : sn + "_c*" });
                                break;
                            }
                        case MetadataUsageType.Type:
                            json.ScriptMetadata.Add(new ScriptMetadata { Address = rva, Name = DisplayName(u.AsType()) + "_var", Signature = "Il2CppType*" });
                            break;
                        case MetadataUsageType.MethodDef:
                            {
                                var m = u.AsMethod();
                                json.ScriptMetadataMethod.Add(new ScriptMetadataMethod
                                {
                                    Address = rva,
                                    Name = "Method$" + TypeDefDisplayName(m.DeclaringType) + "." + m.Name + "()",
                                    MethodAddress = m.MethodPointer != 0 ? bin.GetRva(m.MethodPointer) : 0,
                                });
                                break;
                            }
                        case MetadataUsageType.MethodRef:
                            {
                                var r = u.AsGenericMethodRef();
                                ulong maddr = 0;
                                if (r.GenericVariantPtr != 0) maddr = bin.GetRva(r.GenericVariantPtr);
                                json.ScriptMetadataMethod.Add(new ScriptMetadataMethod
                                {
                                    Address = rva,
                                    Name = "Method$" + TypeDefDisplayName(r.DeclaringType) + GenericArgs(r.TypeGenericParams) + "." + r.BaseMethod.Name + GenericArgs(r.MethodGenericParams) + "()",
                                    MethodAddress = maddr,
                                });
                                break;
                            }
                        case MetadataUsageType.FieldInfo:
                            {
                                var f = u.AsField();
                                json.ScriptMetadata.Add(new ScriptMetadata { Address = rva, Name = "Field$" + TypeDefDisplayName(f.DeclaringType) + "." + f.Name });
                                break;
                            }
                        case MetadataUsageType.StringLiteral:
                            json.ScriptString.Add(new ScriptString { Address = rva, Value = u.AsLiteral() ?? "" });
                            break;
                    }
                }
                catch (Exception ex)
                {
                    log?.Invoke($"[il2cpp] usage {u.Type} at 0x{u.Offset:X}: {ex.Message}");
                }
            }

            private string StructName(Il2CppTypeReflectionData r)
            {
                if (r == null) return "System_Object";
                if (r.isArray)
                {
                    var elem = StructName(r.arrayType);
                    var name = elem + "_array";
                    if (arrayNames.Add(name))
                        arrayHeader.Append("struct ").Append(name).Append(" {\n\tIl2CppObject obj;\n\tIl2CppArrayBounds *bounds;\n\til2cpp_array_size_t max_length;\n\t")
                            .Append(ElemCType(r.arrayType)).Append(" m_Items[65535];\n};\n");
                    return name;
                }
                if (!r.isType || r.baseType == null) return "System_Object";
                if (r.isGenericType && r.genericParams != null && r.genericParams.Length > 0)
                {
                    var key = FixName(StripArity(structNameDic.TryGetValue(r.baseType, out var bn) ? bn : TypeDefDisplayName(r.baseType)))
                              + "_" + string.Join("_", r.genericParams.Select(p => FixName(DisplayName(p)))) + "_";
                    if (!genericStructNames.TryGetValue(key, out var name))
                    {
                        name = Unique(key);
                        genericStructNames[key] = name;
                        pendingGenerics[name] = (r.baseType, null); // no Il2CppGenericInst available here: emit with open generic params
                    }
                    return name;
                }
                return structNameDic.TryGetValue(r.baseType, out var n) ? n : "System_Object";
            }

            private string ElemCType(Il2CppTypeReflectionData r)
            {
                if (r == null || !r.isType || r.baseType == null) return r != null && r.isArray ? StructName(r) + "*" : "Il2CppObject*";
                var td = r.baseType;
                if (td.IsEnumType && td.EnumUnderlyingType != null) return ParseType(td.EnumUnderlyingType, null, null);
                if (td.IsValueType) return StructName(r) + "_o";
                return StructName(r) + "_o*";
            }

