        #region Generator

        private sealed class StructInfo
        {
            public string TypeName;
            public bool IsValueType;
            public string Parent;
            public readonly List<(string type, string name, bool isValueType, bool isCustom)> Fields = new List<(string, string, bool, bool)>();
            public readonly List<(string type, string name, bool isValueType, bool isCustom)> StaticFields = new List<(string, string, bool, bool)>();
            public string[] VTable = Array.Empty<string>();
        }

        private sealed class Generator
        {
            private readonly Action<string> log;
            private readonly string binaryPath;
            private readonly Il2CppBinary bin = LibCpp2IlMain.Binary;
            private readonly Il2CppMetadata md = LibCpp2IlMain.TheMetadata;
            private readonly float mv = LibCpp2IlMain.MetadataVersion;

            private readonly Dictionary<Il2CppTypeDefinition, string> structNameDic = new Dictionary<Il2CppTypeDefinition, string>();
            private readonly HashSet<string> structNameSet = new HashSet<string>(StringComparer.Ordinal);
            private readonly Dictionary<string, StructInfo> structByName = new Dictionary<string, StructInfo>(StringComparer.Ordinal);
            private readonly List<StructInfo> structList = new List<StructInfo>();
            private readonly HashSet<StructInfo> emitted = new HashSet<StructInfo>();
            private readonly Dictionary<string, (Il2CppTypeDefinition def, Il2CppGenericInst inst)> pendingGenerics = new Dictionary<string, (Il2CppTypeDefinition, Il2CppGenericInst)>(StringComparer.Ordinal);
            private readonly Dictionary<string, string> genericStructNames = new Dictionary<string, string>(StringComparer.Ordinal); // key -> struct name
            private readonly StringBuilder arrayHeader = new StringBuilder();
            private readonly HashSet<string> arrayNames = new HashSet<string>(StringComparer.Ordinal);

            public Generator(Action<string> log, string binaryPath) { this.log = log; this.binaryPath = binaryPath; }

            public Il2CppInfo Run(string folder)
            {
                var info = new Il2CppInfo { MetadataVersion = mv, PointerSize = PointerSize() };
                var json = new ScriptJson();

                // 1) unique struct names for every type definition
                foreach (var td in md.typeDefs)
                    structNameDic[td] = Unique(FixName(TypeDefDisplayName(td)));

                // 2) methods
                ulong imageBase = 0;
                foreach (var td in md.typeDefs)
                {
                    AddStruct(td);
                    var typeName = TypeDefDisplayName(td);
                    foreach (var m in td.Methods ?? Array.Empty<Il2CppMethodDefinition>())
                    {
                        if (m.MethodPointer == 0) continue;
                        if (imageBase == 0 && m.Rva != 0 && m.MethodPointer > m.Rva) imageBase = m.MethodPointer - m.Rva;
                        var sm = new ScriptMethod { Address = bin.GetRva(m.MethodPointer), Name = typeName + "$$" + m.Name };
                        BuildSignature(sm, m, td, null, null);
                        json.ScriptMethod.Add(sm);
                    }
                }
                info.Methods = json.ScriptMethod.Count;

                // generic method instantiations
                foreach (var pair in bin.ConcreteGenericImplementationsByAddress)
                {
                    if (pair.Key == 0 || pair.Value == null || pair.Value.Count == 0) continue;
                    var r = pair.Value[0];
                    try
                    {
                        var typeName = TypeDefDisplayName(r.DeclaringType) + GenericArgs(r.TypeGenericParams);
                        var methodName = r.BaseMethod.Name + GenericArgs(r.MethodGenericParams);
                        var sm = new ScriptMethod { Address = bin.GetRva(pair.Key), Name = typeName + "$$" + methodName };
                        BuildSignature(sm, r.BaseMethod, r.DeclaringType, null, null);
                        json.ScriptMethod.Add(sm);
                        info.GenericMethods++;
                    }
                    catch (Exception ex)
                    {
                        log?.Invoke($"[il2cpp] generic method at 0x{pair.Key:X}: {ex.Message}");
                    }
                }
                info.ImageBase = "0x" + imageBase.ToString("X");

                // 3) function starts
                var pointers = new HashSet<ulong>();
                foreach (var td in md.typeDefs)
                    foreach (var m in td.Methods ?? Array.Empty<Il2CppMethodDefinition>())
                        if (m.MethodPointer != 0) pointers.Add(m.MethodPointer);
                foreach (var k in bin.ConcreteGenericImplementationsByAddress.Keys) pointers.Add(k);
                if (mv < 29 && bin.AllCustomAttributeGenerators != null)
                    foreach (var p in bin.AllCustomAttributeGenerators) pointers.Add(p);
                for (var i = 0; i < md.imageDefinitions.Length; i++)
                {
                    try
                    {
                        var ptrs = bin.GetCodegenModuleMethodPointers(i);
                        if (ptrs != null) foreach (var p in ptrs) pointers.Add(p);
                    }
                    catch { /* pre-24.2 has no codegen modules */ }
                }
                pointers.Remove(0);
                json.Addresses = pointers.Select(p => bin.GetRva(p)).OrderBy(x => x).ToArray();
                info.FunctionStarts = json.Addresses.Length;

                // 4) metadata usages (type infos, method infos, field infos, string literals)
                foreach (var u in EnumerateMetadataUsages())
                    AddUsage(json, u);
                info.Strings = json.ScriptString.Count;
                info.MetadataSymbols = json.ScriptMetadata.Count;
                info.MetadataMethods = json.ScriptMetadataMethod.Count;

                // 5) write json
                var settings = new JsonSerializerSettings { Formatting = Formatting.Indented };
                File.WriteAllText(Path.Combine(folder, "script.json"), JsonConvert.SerializeObject(json, settings));
                var literals = json.ScriptString.Select(s => new { value = s.Value, address = "0x" + s.Address.ToString("X") }).ToArray();
                File.WriteAllText(Path.Combine(folder, "stringliteral.json"), JsonConvert.SerializeObject(literals, settings), new UTF8Encoding(false));

                // 6) header
                // generic instances discovered while parsing signatures/fields (may discover more while emitting)
                var header = new StringBuilder();
                var progress = true;
                while (progress)
                {
                    progress = false;
                    foreach (var kv in pendingGenerics.ToList())
                    {
                        if (structByName.ContainsKey(kv.Key + "_o")) continue;
                        AddGenericStruct(kv.Key, kv.Value.def, kv.Value.inst);
                        progress = true;
                    }
                }
                foreach (var si in structList)
                    header.Append(Emit(si));
                info.Structs = structList.Count;

                var sb = new StringBuilder();
                sb.Append("// Generated by UnityRift (formats after Il2CppDumper). Metadata version ").Append(mv).Append("\r\n");
                sb.Append(Il2CppHeaderConstants.GenericHeader);
                string note = null;
                if (mv == 22) sb.Append(Il2CppHeaderConstants.HeaderV22);
                else if (mv < 24.1f) sb.Append(Il2CppHeaderConstants.HeaderV240);
                else if (mv < 24.2f) sb.Append(Il2CppHeaderConstants.HeaderV241);
                else if (mv < 27) sb.Append(Il2CppHeaderConstants.HeaderV242);
                else if (mv < 29) sb.Append(Il2CppHeaderConstants.HeaderV27);
                else
                {
                    sb.Append(Il2CppHeaderConstants.HeaderV29);
                    if (mv > 31)
                    {
                        note = $"metadata v{mv} is newer than the known Il2CppClass layouts; the v29 layout (Il2CppClass_1/_2) is used and may be slightly off for Il2CppClass internals. Object/field layouts (_o/_Fields) come from real field offsets and are unaffected.";
                        sb.Append("// NOTE: ").Append(note).Append("\r\n");
                    }
                }
                info.HeaderVersionNote = note;
                sb.Append(header);
                sb.Append(arrayHeader);
                var h = sb.ToString();
                File.WriteAllText(Path.Combine(folder, "il2cpp.h"), h);
                File.WriteAllText(Path.Combine(folder, "il2cpp_ghidra.h"), GhidraHeaderPrefix + Regex.Replace(h, @": (\w+) \{", "{\n\t$1 super;"));
                return info;
            }

            private const string GhidraHeaderPrefix =
                "typedef unsigned __int8 uint8_t;\ntypedef unsigned __int16 uint16_t;\ntypedef unsigned __int32 uint32_t;\ntypedef unsigned __int64 uint64_t;\n" +
                "typedef __int8 int8_t;\ntypedef __int16 int16_t;\ntypedef __int32 int32_t;\ntypedef __int64 int64_t;\n" +
                "typedef __int64 intptr_t;\ntypedef __int64 uintptr_t;\ntypedef unsigned __int64 size_t;\ntypedef _Bool bool;\n";

            #region names

            private int PointerSize()
            {
                try
                {
                    var p = bin.GetType().GetProperty("is32Bit", BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance)
                            ?? typeof(Il2CppBinary).GetProperty("is32Bit", BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
                    if (p != null && p.GetValue(bin) is bool b) return b ? 4 : 8;
                    var f = bin.GetType().GetField("is32Bit", BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.FlattenHierarchy);
                    if (f != null && f.GetValue(bin) is bool b2) return b2 ? 4 : 8;
                }
                catch { /* ignore */ }
                return 8;
            }

            private static readonly HashSet<string> CKeywords = new HashSet<string>
            {
                "auto","break","case","char","const","continue","default","do","double","else","enum","extern","float","for","goto","if",
                "int","long","register","return","short","signed","sizeof","static","struct","switch","typedef","union","unsigned","void",
                "volatile","while","bool","class","new","delete","this","template","typename","namespace","using","try","catch","throw",
                "inline","virtual","public","private","protected","friend","operator","true","false","near","far","huge","interrupt",
                "cdecl","stdcall","fastcall","thiscall","pascal","asm","export","import","module","in","out","ref",
            };

            private static string FixName(string s)
            {
                if (string.IsNullOrEmpty(s)) return "_";
                if (CKeywords.Contains(s)) return "_" + s;
                var r = Regex.Replace(s, "[^a-zA-Z0-9_]", "_");
                return char.IsDigit(r[0]) ? "_" + r : r;
            }

            private string Unique(string name)
            {
                var n = name;
                var i = 1;
                while (!structNameSet.Add(n)) n = $"{name}_{i++}";
                return n;
            }

            /// <summary>Namespace.Outer.Inner (arity kept, e.g. List`1) — used for symbol names.</summary>
            private static string TypeDefDisplayName(Il2CppTypeDefinition td)
            {
                var chain = new List<string>();
                var t = td;
                var guard = 0;
                while (t != null && guard++ < 32)
                {
                    chain.Add(t.Name);
                    t = t.DeclaringType;
                }
                chain.Reverse();
                var ns = td.Namespace;
                var root = td;
                guard = 0;
                while (root.DeclaringType != null && guard++ < 32) root = root.DeclaringType;
                ns = root.Namespace;
                return (string.IsNullOrEmpty(ns) ? "" : ns + ".") + string.Join(".", chain);
            }

            private string DisplayName(Il2CppTypeReflectionData r)
            {
                if (r == null) return "?";
                if (r.isArray) return DisplayName(r.arrayType) + "[" + new string(',', Math.Max(0, r.arrayRank - 1)) + "]";
                if (r.isPointer && r.arrayType != null) return DisplayName(r.arrayType) + "*";
                if (!r.isType) return r.variableGenericParamName ?? "T";
                var name = r.baseType != null ? TypeDefDisplayName(r.baseType) : "?";
                if (r.isGenericType && r.genericParams != null && r.genericParams.Length > 0)
                    name = StripArity(name) + "<" + string.Join(", ", r.genericParams.Select(DisplayName)) + ">";
                return name;
            }

            private string GenericArgs(Il2CppTypeReflectionData[] args)
            {
                if (args == null || args.Length == 0) return "";
                return "<" + string.Join(", ", args.Select(DisplayName)) + ">";
            }

            private static string StripArity(string name)
            {
                var i = name.IndexOf('`');
                return i < 0 ? name : Regex.Replace(name, "`[0-9]+", "");
            }

            /// <summary>C# style display name of an Il2CppType (used for metadata symbol names).</summary>
            private string DisplayName(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                switch (t.Type)
                {
                    case Il2CppTypeEnum.IL2CPP_TYPE_VOID: return "System.Void";
                    case Il2CppTypeEnum.IL2CPP_TYPE_BOOLEAN: return "System.Boolean";
                    case Il2CppTypeEnum.IL2CPP_TYPE_CHAR: return "System.Char";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I1: return "System.SByte";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U1: return "System.Byte";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I2: return "System.Int16";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U2: return "System.UInt16";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I4: return "System.Int32";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U4: return "System.UInt32";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I8: return "System.Int64";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U8: return "System.UInt64";
                    case Il2CppTypeEnum.IL2CPP_TYPE_R4: return "System.Single";
                    case Il2CppTypeEnum.IL2CPP_TYPE_R8: return "System.Double";
                    case Il2CppTypeEnum.IL2CPP_TYPE_STRING: return "System.String";
                    case Il2CppTypeEnum.IL2CPP_TYPE_OBJECT: return "System.Object";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I: return "System.IntPtr";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U: return "System.UIntPtr";
                    case Il2CppTypeEnum.IL2CPP_TYPE_TYPEDBYREF: return "System.TypedReference";
                    case Il2CppTypeEnum.IL2CPP_TYPE_PTR: return DisplayName(t.GetEncapsulatedType(), classInst, methodInst) + "*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_BYREF: return DisplayName(t.GetEncapsulatedType(), classInst, methodInst) + "&";
                    case Il2CppTypeEnum.IL2CPP_TYPE_SZARRAY: return DisplayName(t.GetEncapsulatedType(), classInst, methodInst) + "[]";
                    case Il2CppTypeEnum.IL2CPP_TYPE_ARRAY: return DisplayName(t.GetArrayElementType(), classInst, methodInst) + "[" + new string(',', Math.Max(0, t.GetArrayRank() - 1)) + "]";
                    case Il2CppTypeEnum.IL2CPP_TYPE_VALUETYPE:
                    case Il2CppTypeEnum.IL2CPP_TYPE_CLASS:
                        return TypeDefDisplayName(t.AsClass());
                    case Il2CppTypeEnum.IL2CPP_TYPE_GENERICINST:
                        {
                            var gc = t.GetGenericClass();
                            var args = gc.Context?.ClassInst?.Types ?? Array.Empty<Il2CppType>();
                            return StripArity(TypeDefDisplayName(gc.TypeDefinition)) + "<" + string.Join(", ", args.Select(a => DisplayName(a, classInst, methodInst))) + ">";
                        }
                    case Il2CppTypeEnum.IL2CPP_TYPE_VAR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_MVAR:
                        {
                            var resolved = ResolveGenericParam(t, classInst, methodInst);
                            if (resolved != null) return DisplayName(resolved, null, null);
                            try { return t.GetGenericParameterDef()?.Name ?? "T"; } catch { return "T"; }
                        }
                    default:
                        return t.Type.ToString();
                }
            }

            private static Il2CppType ResolveGenericParam(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                var inst = t.Type == Il2CppTypeEnum.IL2CPP_TYPE_VAR ? classInst : (methodInst ?? classInst);
                if (inst == null) return null;
                try
                {
                    var gp = t.GetGenericParameterDef();
                    var idx = gp.genericParameterIndexInOwner;
                    var types = inst.Types;
                    if (types != null && idx < types.Length) return types[idx];
                }
                catch { /* ignore */ }
                return null;
            }

            #endregion

            #region C types

            /// <summary>Base struct name (without _o/_c suffix) for a type; registers arrays/generic instances on the way.</summary>
            private string StructName(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                switch (t.Type)
                {
                    case Il2CppTypeEnum.IL2CPP_TYPE_PTR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_BYREF:
                        return StructName(t.GetEncapsulatedType(), classInst, methodInst);
                    case Il2CppTypeEnum.IL2CPP_TYPE_SZARRAY:
                        return ArrayStruct(t.GetEncapsulatedType(), classInst, methodInst);
                    case Il2CppTypeEnum.IL2CPP_TYPE_ARRAY:
                        return ArrayStruct(t.GetArrayElementType(), classInst, methodInst);
                    case Il2CppTypeEnum.IL2CPP_TYPE_GENERICINST:
                        return GenericStructName(t, classInst, methodInst);
                    case Il2CppTypeEnum.IL2CPP_TYPE_VAR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_MVAR:
                        {
                            var r = ResolveGenericParam(t, classInst, methodInst);
                            return r != null ? StructName(r, null, null) : "System_Object";
                        }
                    default:
                        {
                            var td = TypeDefOf(t);
                            return td != null && structNameDic.TryGetValue(td, out var n) ? n : "System_Object";
                        }
                }
            }

            private Il2CppTypeDefinition TypeDefOf(Il2CppType t)
            {
                try
                {
                    switch (t.Type)
                    {
                        case Il2CppTypeEnum.IL2CPP_TYPE_VALUETYPE:
                        case Il2CppTypeEnum.IL2CPP_TYPE_CLASS:
                            return t.AsClass();
                        case Il2CppTypeEnum.IL2CPP_TYPE_GENERICINST:
                            return t.GetGenericClass().TypeDefinition;
                        default:
                            return t.CoerceToUnderlyingTypeDefinition();
                    }
                }
                catch
                {
                    return null;
                }
            }

            private string ArrayStruct(Il2CppType elem, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                var elemStruct = StructName(elem, classInst, methodInst);
                var name = elemStruct + "_array";
                if (arrayNames.Add(name))
                {
                    arrayHeader.Append("struct ").Append(name).Append(" {\n\tIl2CppObject obj;\n\tIl2CppArrayBounds *bounds;\n\til2cpp_array_size_t max_length;\n\t")
                        .Append(ParseType(elem, classInst, methodInst)).Append(" m_Items[65535];\n};\n");
                }
                return name;
            }

            private string GenericStructName(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                var gc = t.GetGenericClass();
                var td = gc.TypeDefinition;
                var inst = gc.Context?.ClassInst;
                var args = inst?.Types ?? Array.Empty<Il2CppType>();
                var key = FixName(StripArity(structNameDic.TryGetValue(td, out var baseName) ? baseName : TypeDefDisplayName(td)))
                          + "_" + string.Join("_", args.Select(a => FixName(DisplayName(a, classInst, methodInst)))) + "_";
                if (!genericStructNames.TryGetValue(key, out var name))
                {
                    name = Unique(key);
                    genericStructNames[key] = name;
                    // Resolve VAR/MVAR args against the current context so the struct has concrete field types.
                    if (inst != null && args.Any(a => a.Type == Il2CppTypeEnum.IL2CPP_TYPE_VAR || a.Type == Il2CppTypeEnum.IL2CPP_TYPE_MVAR))
                        pendingGenerics[name] = (td, null);
                    else
                        pendingGenerics[name] = (td, inst);
                }
                return name;
            }

            /// <summary>C type used for fields/parameters (Il2CppDumper's ParseType).</summary>
            private string ParseType(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                switch (t.Type)
                {
                    case Il2CppTypeEnum.IL2CPP_TYPE_VOID: return "void";
                    case Il2CppTypeEnum.IL2CPP_TYPE_BOOLEAN: return "bool";
                    case Il2CppTypeEnum.IL2CPP_TYPE_CHAR: return "uint16_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I1: return "int8_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U1: return "uint8_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I2: return "int16_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U2: return "uint16_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I4: return "int32_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U4: return "uint32_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I8: return "int64_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U8: return "uint64_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_R4: return "float";
                    case Il2CppTypeEnum.IL2CPP_TYPE_R8: return "double";
                    case Il2CppTypeEnum.IL2CPP_TYPE_STRING: return "System_String_o*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I: return "intptr_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_U: return "uintptr_t";
                    case Il2CppTypeEnum.IL2CPP_TYPE_OBJECT:
                    case Il2CppTypeEnum.IL2CPP_TYPE_TYPEDBYREF:
                        return "Il2CppObject*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_PTR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_BYREF:
                        return ParseType(t.GetEncapsulatedType(), classInst, methodInst) + "*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_SZARRAY:
                        return ArrayStruct(t.GetEncapsulatedType(), classInst, methodInst) + "*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_ARRAY:
                        return ArrayStruct(t.GetArrayElementType(), classInst, methodInst) + "*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_VALUETYPE:
                        {
                            var td = t.AsClass();
                            if (td.IsEnumType && td.EnumUnderlyingType != null) return ParseType(td.EnumUnderlyingType, classInst, methodInst);
                            return structNameDic[td] + "_o";
                        }
                    case Il2CppTypeEnum.IL2CPP_TYPE_CLASS:
                        return structNameDic[t.AsClass()] + "_o*";
                    case Il2CppTypeEnum.IL2CPP_TYPE_GENERICINST:
                        {
                            var td = t.GetGenericClass().TypeDefinition;
                            var name = GenericStructName(t, classInst, methodInst);
                            if (td.IsValueType)
                            {
                                if (td.IsEnumType && td.EnumUnderlyingType != null) return ParseType(td.EnumUnderlyingType, classInst, methodInst);
                                return name + "_o";
                            }
                            return name + "_o*";
                        }
                    case Il2CppTypeEnum.IL2CPP_TYPE_VAR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_MVAR:
                        {
                            var r = ResolveGenericParam(t, classInst, methodInst);
                            return r != null ? ParseType(r, null, null) : "Il2CppObject*";
                        }
                    default:
                        return "void*";
                }
            }

            private bool IsValueTypeStruct(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                switch (t.Type)
                {
                    case Il2CppTypeEnum.IL2CPP_TYPE_VALUETYPE: return !t.AsClass().IsEnumType;
                    case Il2CppTypeEnum.IL2CPP_TYPE_GENERICINST: { var td = t.GetGenericClass().TypeDefinition; return td.IsValueType && !td.IsEnumType; }
                    case Il2CppTypeEnum.IL2CPP_TYPE_VAR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_MVAR: { var r = ResolveGenericParam(t, classInst, methodInst); return r != null && IsValueTypeStruct(r, null, null); }
                    default: return false;
                }
            }

            private bool IsCustomType(Il2CppType t, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                switch (t.Type)
                {
                    case Il2CppTypeEnum.IL2CPP_TYPE_PTR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_BYREF: return IsCustomType(t.GetEncapsulatedType(), classInst, methodInst);
                    case Il2CppTypeEnum.IL2CPP_TYPE_STRING:
                    case Il2CppTypeEnum.IL2CPP_TYPE_CLASS:
                    case Il2CppTypeEnum.IL2CPP_TYPE_ARRAY:
                    case Il2CppTypeEnum.IL2CPP_TYPE_SZARRAY: return true;
                    case Il2CppTypeEnum.IL2CPP_TYPE_VALUETYPE: return !t.AsClass().IsEnumType;
                    case Il2CppTypeEnum.IL2CPP_TYPE_GENERICINST: return !t.GetGenericClass().TypeDefinition.IsEnumType;
                    case Il2CppTypeEnum.IL2CPP_TYPE_VAR:
                    case Il2CppTypeEnum.IL2CPP_TYPE_MVAR: { var r = ResolveGenericParam(t, classInst, methodInst); return r != null && IsCustomType(r, null, null); }
                    default: return false;
                }
            }

            private static string TypeSigChar(Il2CppType t, bool byref)
            {
                if (byref) return "i";
                switch (t.Type)
                {
                    case Il2CppTypeEnum.IL2CPP_TYPE_VOID: return "v";
                    case Il2CppTypeEnum.IL2CPP_TYPE_I8:
                    case Il2CppTypeEnum.IL2CPP_TYPE_U8: return "j";
                    case Il2CppTypeEnum.IL2CPP_TYPE_R4: return "f";
                    case Il2CppTypeEnum.IL2CPP_TYPE_R8: return "d";
                    default: return "i";
                }
            }

            private void BuildSignature(ScriptMethod sm, Il2CppMethodDefinition m, Il2CppTypeDefinition declaring, Il2CppGenericInst classInst, Il2CppGenericInst methodInst)
            {
                var sig = new StringBuilder();
                var tsig = new StringBuilder();
                string ret;
                try
                {
                    var rt = m.RawReturnType;
                    ret = ParseType(rt, classInst, methodInst) + (rt.Byref != 0 ? "*" : "");
                    tsig.Append(TypeSigChar(rt, rt.Byref != 0));
                }
                catch
                {
                    ret = "void*";
                    tsig.Append('i');
                }
                var ps = new List<string>();
                if (!m.IsStatic)
                {
                    var thisName = structNameDic.TryGetValue(declaring, out var sn) ? sn : "Il2CppObject";
                    ps.Add((declaring.IsValueType ? thisName + "_o*" : thisName + "_o*") + " __this");
                    tsig.Append('i');
                }
                else if (mv <= 24)
                {
                    ps.Add("Il2CppObject* __this");
                    tsig.Append('i');
                }
                Il2CppParameterReflectionData[] pars = null;
                try { pars = m.Parameters; } catch { /* ignore */ }
                var i = 0;
                foreach (var p in pars ?? Array.Empty<Il2CppParameterReflectionData>())
                {
                    string ct;
                    var byref = false;
                    try
                    {
                        byref = p.RawType.Byref != 0;
                        ct = ParseType(p.RawType, classInst, methodInst) + (byref ? "*" : "");
                        tsig.Append(TypeSigChar(p.RawType, byref));
                    }
                    catch
                    {
                        ct = "void*";
                        tsig.Append('i');
                    }
                    var pname = string.IsNullOrEmpty(p.ParameterName) ? "p" + i : p.ParameterName;
                    ps.Add(ct + " " + FixName(pname));
                    i++;
                }
                ps.Add("const MethodInfo* method");
                tsig.Append('i');
                sig.Append(ret).Append(' ').Append(FixName(sm.Name)).Append(" (").Append(string.Join(", ", ps)).Append(");");
                sm.Signature = sig.ToString();
                sm.TypeSignature = tsig.ToString();
            }

