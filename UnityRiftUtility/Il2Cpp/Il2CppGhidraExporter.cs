            private void AddStruct(Il2CppTypeDefinition td)
            {
                var si = new StructInfo { TypeName = structNameDic[td], IsValueType = td.IsValueType };
                Fill(si, td, null);
                Register(si);
            }

            private void AddGenericStruct(string name, Il2CppTypeDefinition td, Il2CppGenericInst inst)
            {
                var si = new StructInfo { TypeName = name, IsValueType = td.IsValueType };
                Fill(si, td, inst);
                Register(si);
            }

            private void Register(StructInfo si)
            {
                structList.Add(si);
                structByName[si.TypeName + "_o"] = si;
            }

            private void Fill(StructInfo si, Il2CppTypeDefinition td, Il2CppGenericInst inst)
            {
                // parent
                if (!td.IsValueType && !td.IsEnumType)
                {
                    try
                    {
                        var parent = td.RawBaseType;
                        if (parent != null && parent.Type != Il2CppTypeEnum.IL2CPP_TYPE_OBJECT)
                            si.Parent = StructName(parent, inst, null);
                    }
                    catch { /* ignore */ }
                }
                // fields
                var seen = new HashSet<string>(StringComparer.Ordinal);
                Il2CppFieldReflectionData[] fields = null;
                try { fields = td.FieldInfos; } catch { /* ignore */ }
                var idx = 0;
                foreach (var f in fields ?? Array.Empty<Il2CppFieldReflectionData>())
                {
                    idx++;
                    if ((f.Attributes & System.Reflection.FieldAttributes.Literal) != 0) continue;
                    var ft = f.Field.RawFieldType;
                    string ctype;
                    bool isVt, isCustom;
                    try
                    {
                        ctype = ParseType(ft, inst, null);
                        isVt = IsValueTypeStruct(ft, inst, null);
                        isCustom = IsCustomType(ft, inst, null);
                    }
                    catch
                    {
                        ctype = "void*"; isVt = false; isCustom = false;
                    }
                    var name = FixName(f.Field.Name);
                    if (!seen.Add(name)) name = $"_{idx}_{name}";
                    var entry = (ctype, name, isVt, isCustom);
                    if ((f.Attributes & System.Reflection.FieldAttributes.Static) != 0) si.StaticFields.Add(entry);
                    else si.Fields.Add(entry);
                }
                // vtable
                try
                {
                    var vt = td.VTable;
                    if (vt != null && vt.Length > 0)
                    {
                        var slots = new SortedDictionary<int, string>();
                        foreach (var u in vt)
                        {
                            if (u == null) continue;
                            Il2CppMethodDefinition mdef = null;
                            try
                            {
                                if (u.Type == MetadataUsageType.MethodDef) mdef = u.AsMethod();
                                else if (u.Type == MetadataUsageType.MethodRef) mdef = u.AsGenericMethodRef()?.BaseMethod;
                            }
                            catch { /* ignore */ }
                            if (mdef == null || mdef.slot == ushort.MaxValue) continue;
                            slots[mdef.slot] = FixName(mdef.Name);
                        }
                        if (slots.Count > 0)
                        {
                            si.VTable = new string[slots.Keys.Last() + 1];
                            foreach (var kv in slots) si.VTable[kv.Key] = kv.Value;
                        }
                    }
                }
                catch { /* ignore */ }
            }

            private string Emit(StructInfo si)
            {
                if (!emitted.Add(si)) return "";
                var pre = new StringBuilder();
                var sb = new StringBuilder();
                if (si.Parent != null && structByName.TryGetValue(si.Parent + "_o", out var parentInfo))
                {
                    pre.Append(Emit(parentInfo));
                    sb.Append("struct ").Append(si.TypeName).Append("_Fields : ").Append(si.Parent).Append("_Fields {\n");
                }
                else
                {
                    sb.Append("struct ").Append(si.TypeName).Append("_Fields {\n");
                }
                foreach (var f in si.Fields)
                {
                    if (f.isValueType && structByName.TryGetValue(f.type, out var fi)) pre.Append(Emit(fi));
                    sb.Append('\t').Append(f.isCustom ? "struct " : "").Append(f.type).Append(' ').Append(f.name).Append(";\n");
                }
                sb.Append("};\n");

                if (si.VTable.Length > 0)
                {
                    sb.Append("struct ").Append(si.TypeName).Append("_VTable {\n");
                    for (var i = 0; i < si.VTable.Length; i++)
                        sb.Append("\tVirtualInvokeData _").Append(i).Append('_').Append(si.VTable[i] ?? "unknown").Append(";\n");
                    sb.Append("};\n");
                }

                sb.Append("struct ").Append(si.TypeName).Append("_c {\n\tIl2CppClass_1 _1;\n");
                sb.Append(si.StaticFields.Count > 0 ? "\tstruct " + si.TypeName + "_StaticFields* static_fields;\n" : "\tvoid* static_fields;\n");
                sb.Append("\tIl2CppRGCTXData* rgctx_data;\n\tIl2CppClass_2 _2;\n");
                sb.Append(si.VTable.Length > 0 ? "\t" + si.TypeName + "_VTable vtable;\n" : "\tVirtualInvokeData vtable[32];\n");
                sb.Append("};\n");

                sb.Append("struct ").Append(si.TypeName).Append("_o {\n");
                if (!si.IsValueType)
                    sb.Append('\t').Append(si.TypeName).Append("_c *klass;\n\tvoid *monitor;\n");
                sb.Append('\t').Append(si.TypeName).Append("_Fields fields;\n};\n");

                if (si.StaticFields.Count > 0)
                {
                    sb.Append("struct ").Append(si.TypeName).Append("_StaticFields {\n");
                    foreach (var f in si.StaticFields)
                    {
                        if (f.isValueType && structByName.TryGetValue(f.type, out var fi)) pre.Append(Emit(fi));
                        sb.Append('\t').Append(f.isCustom ? "struct " : "").Append(f.type).Append(' ').Append(f.name).Append(";\n");
                    }
                    sb.Append("};\n");
                }
                return pre.Append(sb).ToString();
            }

